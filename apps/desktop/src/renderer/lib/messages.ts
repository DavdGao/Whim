/**
 * Look up a plugin-provided string for the locale, falling back to English, then to `fallback`.
 * @param locales The plugin's catalogs.
 * @param locale The active locale.
 * @param key The catalog key.
 * @param fallback Text used when no catalog has the key.
 * @returns The string.
 */
export function pluginText(
    locales: Readonly<Record<string, Readonly<Record<string, string>>>> | undefined,
    locale: Locale,
    key: string,
    fallback: string
): string {
    return locales?.[locale]?.[key] ?? locales?.en?.[key] ?? fallback;
}
